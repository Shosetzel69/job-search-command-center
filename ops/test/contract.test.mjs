test('N26 public execution evidence excludes private execution identity and free text',()=>{
  const input={
    operation_id:'op-test-1234567890',
    execution_name:'jscc-diagnostics-dev-abc123',
    assertions:{
      target_alias:'jscc-search-dev-rrbgb',
      task_count:1,
      target_exit_code:2,
      target_term_signal:null,
      root_cause:'container exited with code 2',
      raw_status:{secret:true}
    }
  };
  const pub=publicEvidence(input);
  assert.equal('execution_name' in pub,false);
  assert.equal('root_cause' in pub.assertions,false);
  assert.deepEqual(pub.assertions,{
    target_alias:'jscc-search-dev-rrbgb',
    task_count:1,
    target_exit_code:2,
    target_term_signal:null
  });
  const auth=authenticatedEvidence(input);
  assert.equal(auth.execution_name,'jscc-diagnostics-dev-abc123');
  assert.equal(auth.assertions.root_cause,'container exited with code 2');
});


